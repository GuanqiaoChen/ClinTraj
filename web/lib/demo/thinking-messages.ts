const PHASES: readonly ThinkingPhase[] = ["evidence", "differential", "priorities", "candidates"];

export function getTourThinkingMessage(round: number, progress: number, seed: number): string {
  const roundIndex = Math.min(TOUR_THINKING_MESSAGES.length - 1, Math.max(0, Math.trunc(round) - 1));
  const slot = Math.min(7, Math.max(0, Math.floor(progress * 8)));
  const phaseIndex = Math.floor(slot / 2);
  const pool = TOUR_THINKING_MESSAGES[roundIndex][PHASES[phaseIndex]];
  // Stable while paused or seeking; a new replay seed chooses a new pair in each phase.
  let hash = (seed ^ Math.imul(roundIndex + 1, 0x9e3779b9) ^ Math.imul(phaseIndex + 1, 0x85ebca6b)) >>> 0;
  hash = Math.imul(hash ^ (hash >>> 16), 0x45d9f3b) >>> 0;
  hash ^= hash >>> 16;
  const first = (hash >>> 0) % pool.length;
  const stride = 1 + ((hash >>> 8) % (pool.length - 1));
  return pool[(first + (slot % 2) * stride) % pool.length];
}
